# -----------------------------
# 1) Модель (Та сама функція, без змін логіки)
# -----------------------------
def simulate_water_cycle(
    steps=120, dt=1.0, temp_c=20.0, wind=2.0, cloud_albedo=0.4,
    humidity0=0.35, water_surface=0.7, plants=0.4,
    infiltration=0.25, runoff=0.20, seed=0
):
    rng = np.random.default_rng(seed)

    S = 70.0 * water_surface
    G = 20.0 * (0.5 + 0.5 * infiltration)
    P = 15.0 * plants
    A = 10.0 * humidity0
    C = 8.0 * (0.4 + 0.6 * humidity0)

    def clip(x): return max(0.0, x)

    solar = 1.0 - 0.6 * cloud_albedo
    temp_factor = np.exp((temp_c - 20.0) / 20.0)
    wind_factor = 0.6 + 0.2 * wind

    evap_base, transp_base, cond_base = 0.18, 0.10, 0.12
    rain_base, baseflow = 0.10, 0.06
    runoff_base, infil_base = runoff, infiltration

    A_hist, C_hist, S_hist, G_hist, P_hist = [], [], [], [], []
    flows = {"E": [], "T": [], "K": [], "R": [], "I": [], "Q": [], "B": []}

    for t in range(steps):
        E = evap_base * solar * temp_factor * wind_factor * (S / (30.0 + S))
        T = transp_base * solar * temp_factor * (0.6 + 0.8 * plants) * (P / (10.0 + P))
        K = cond_base * (A / (5.0 + A)) * (0.8 + 0.4 * (1.0 - temp_factor / (1.0 + temp_factor)))

        rain_noise = 0.85 + 0.3 * rng.random()
        R = rain_base * rain_noise * (C / (6.0 + C))

        to_surface = 0.55
        to_plants = 0.30 * (0.7 + 0.6 * plants)
        to_ground = max(0.05, 1.0 - to_surface - to_plants)

        R_S = R * to_surface
        R_P = R * (to_plants / (to_surface + to_plants + to_ground))
        R_G = R * (to_ground / (to_surface + to_plants + to_ground))

        I = infil_base * (S / (40.0 + S)) * (0.6 + 0.8 * (1.0 - runoff_base))
        Q = runoff_base * (S / (35.0 + S)) * (0.8 + 0.6 * rain_noise)
        B = baseflow * (G / (20.0 + G))

        S = clip(S + dt*(R_S + B - E - I - Q))
        G = clip(G + dt*(R_G + I - B))
        P = clip(P + dt*(R_P - T) + 0.02*(G/(10+G)))
        A = clip(A + dt*(E + T - K))
        C = clip(C + dt*(K - R))

        A_hist.append(A); C_hist.append(C); S_hist.append(S); G_hist.append(G); P_hist.append(P)
        flows["E"].append(E); flows["T"].append(T); flows["K"].append(K); flows["R"].append(R)
        flows["I"].append(I); flows["Q"].append(Q); flows["B"].append(B)

    return {
        "A": np.array(A_hist), "C": np.array(C_hist), "S": np.array(S_hist),
        "G": np.array(G_hist), "P": np.array(P_hist),
        "flows": {k: np.array(v) for k, v in flows.items()}
    }

